"""Caveat A ablation: four-arm prompt-interface experiment.

For a fixed sample of (problem, solution) pairs and a fixed identity
condition set, query the critic under each of four prompt variants:

  - verdict_only_instructed: existing verdict-only system (includes
    explicit "Do NOT attempt to produce a corrected answer" instruction);
    3-field JSON schema.
  - verdict_only_neutral:    neutral review instruction (no "do not"),
    3-field JSON schema.
  - verdict_schema_matched:  same neutral instruction as arm 2;
    4-field JSON schema with corrected_answer always null.
  - verdict_plus_repair:     neutral instruction; full 4-field schema
    with a real corrected_answer generated by the critic.

Critic conditions: anonymous, self, weak_model (three primary
contrasts; the ablation does not need other_model/human/strong_model).

Sample design: for each (critic, dataset), take up to N_WRONG actually
wrong solutions and up to N_CORRECT actually correct solutions from the
existing solutions file, sampled with a fixed seed. The sample IDs are
persisted to logs/caveat_a_samples/<critic>_<dataset>.json so that all
arms run on identical items and the experiment is reproducible.

Outputs:
  logs/<log_dir>/identity_swap_<critic>_on_<solver>_<dataset>__<arm>.jsonl
"""

import argparse
import json
import random
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import asdict
from pathlib import Path

from tqdm import tqdm

from identity_bias.config import IdentityCondition, Dataset, MODEL_PRESETS
from identity_bias.critic.identity_critic import IdentityCritic, CritiqueResult
from identity_bias.critic.prompts import build_caveat_a_messages
from identity_bias.llm import create_llm
from identity_bias.logging.result_logger import ResultLogger


SAMPLES_DIR = Path(__file__).parent.parent / "logs" / "caveat_a_samples"
SAMPLES_DIR.mkdir(parents=True, exist_ok=True)

CONDITION_MAP = {c.value: c for c in IdentityCondition}
ABLATION_ARMS = ["verdict_only_instructed", "verdict_only_neutral",
                 "verdict_schema_matched", "verdict_plus_repair",
                 "verdict_plus_repair_reversed"]


def load_or_lock_sample(critic_model, dataset, solutions_file, n_wrong, n_correct, seed):
    """Pick a fixed sample of (problem_id) for this critic+dataset and
    persist it. The cache filename includes the solutions-file basename so
    that the same critic can run on multiple solver pools (self- vs
    cross-critique) without colliding sample sets."""
    sol_tag = Path(solutions_file).stem  # e.g. solutions_gpt-oss-think_aime
    cache_path = SAMPLES_DIR / f"{critic_model}__{sol_tag}.json"
    # Backwards-compat: prefer the legacy cache only when the solutions file
    # matches what created it (avoids accidentally reusing a different sample).
    legacy_path = SAMPLES_DIR / f"{critic_model}_{dataset}.json"
    if (not cache_path.exists()) and legacy_path.exists():
        with open(legacy_path) as f:
            legacy = json.load(f)
        if legacy.get("solutions_file") == str(solutions_file):
            cache_path = legacy_path
    if cache_path.exists():
        with open(cache_path) as f:
            cached = json.load(f)
        return set(cached["wrong_ids"]), set(cached["correct_ids"]), cached

    problems, solutions = ResultLogger.load_solutions(str(solutions_file))
    wrong_ids = [s.problem_id for s in solutions if not s.is_correct]
    correct_ids = [s.problem_id for s in solutions if s.is_correct]

    rng = random.Random(seed)
    rng.shuffle(wrong_ids)
    rng.shuffle(correct_ids)

    wrong_pick = wrong_ids[:n_wrong]
    correct_pick = correct_ids[:n_correct]

    info = {
        "critic_model": critic_model,
        "dataset": dataset,
        "solutions_file": str(solutions_file),
        "seed": seed,
        "n_wrong_requested": n_wrong,
        "n_correct_requested": n_correct,
        "n_wrong_picked": len(wrong_pick),
        "n_correct_picked": len(correct_pick),
        "wrong_ids": wrong_pick,
        "correct_ids": correct_pick,
    }
    with open(cache_path, "w") as f:
        json.dump(info, f, indent=2)
    return set(wrong_pick), set(correct_pick), info


class AblationCritic(IdentityCritic):
    """Critic that uses one of the Caveat A ablation arms for its single call."""

    def __init__(self, llm, model_name, arm):
        super().__init__(llm, model_name=model_name, two_stage=False)
        self.arm = arm

    def critique(self, problem, solution, identity_condition):
        messages = build_caveat_a_messages(
            question=problem.question,
            chain_of_thought=solution.chain_of_thought,
            final_answer=solution.final_answer,
            identity_condition=identity_condition,
            arm=self.arm,
        )
        response = self.llm.generate(messages)
        parsed = self._parse_response(response.text)
        return CritiqueResult(
            problem_id=problem.id,
            identity_condition=identity_condition.value,
            critic_model=self.model_name,
            solver_model=solution.solver_model,
            is_correct=parsed.get("is_correct", True),
            error_description=parsed.get("error_description"),
            corrected_answer=parsed.get("corrected_answer"),
            confidence=parsed.get("confidence", 0.5),
            actually_correct=solution.is_correct,
            raw_response=response.text,
            prompt_tokens=response.prompt_tokens,
            completion_tokens=response.completion_tokens,
        )


def main():
    parser = argparse.ArgumentParser(description="Caveat A four-arm ablation")
    parser.add_argument("--critic-model", required=True,
                        choices=list(MODEL_PRESETS.keys()))
    parser.add_argument("--solutions-file", required=True)
    parser.add_argument("--dataset", required=True,
                        choices=[d.value for d in Dataset])
    parser.add_argument("--conditions", nargs="+",
                        default=["anonymous", "self", "weak_model"],
                        choices=list(CONDITION_MAP.keys()))
    parser.add_argument("--arms", nargs="+", default=ABLATION_ARMS,
                        choices=ABLATION_ARMS)
    parser.add_argument("--n-wrong", type=int, default=100)
    parser.add_argument("--n-correct", type=int, default=50)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--base-url", default="http://localhost:8000/v1")
    parser.add_argument("--temperature", type=float, default=0.0)
    parser.add_argument("--max-tokens", type=int, default=None,
                        help="Override critic max_tokens (e.g. lower than preset)")
    parser.add_argument("--log-dir", default="logs/caveat_a_ablation")
    parser.add_argument("--workers", type=int, default=8)
    parser.add_argument("--fresh", action="store_true",
                        help="Delete existing logs for this critic/dataset before running")
    args = parser.parse_args()

    wrong_ids, correct_ids, sample_info = load_or_lock_sample(
        args.critic_model, args.dataset, args.solutions_file,
        args.n_wrong, args.n_correct, args.seed,
    )
    picked_ids = wrong_ids | correct_ids
    print(f"sample: {len(wrong_ids)} wrong + {len(correct_ids)} correct"
          f" = {len(picked_ids)} unique items (cache: {sample_info.get('cache') or 'new'})")

    problems_all, solutions_all = ResultLogger.load_solutions(args.solutions_file)
    keep_pairs = [(p, s) for p, s in zip(problems_all, solutions_all)
                  if p.id in picked_ids]
    print(f"loaded {len(keep_pairs)} (problem, solution) pairs after sample filter")
    if not keep_pairs:
        raise SystemExit("no items selected; check sample lock and solutions file")

    config = MODEL_PRESETS[args.critic_model](base_url=args.base_url)
    config.temperature = args.temperature
    if args.max_tokens is not None:
        config.max_tokens = args.max_tokens
    llm = create_llm(config)
    solver_model = keep_pairs[0][1].solver_model

    for arm in args.arms:
        for cond_name in args.conditions:
            cond = CONDITION_MAP[cond_name]
            exp_name = (f"identity_swap_{args.critic_model}_on_{solver_model}"
                        f"_{args.dataset}__{arm}")
            logger = ResultLogger(args.log_dir, exp_name, resume=not args.fresh)
            done = logger.get_completed_ids("critique")

            critic = AblationCritic(llm, args.critic_model, arm=arm)

            todo = [(p, s) for (p, s) in keep_pairs
                    if f"{p.id}_{cond.value}" not in done]
            print(f"\n--- arm={arm} cond={cond.value} "
                  f"already={len(keep_pairs)-len(todo)} remaining={len(todo)} ---")
            if not todo:
                continue

            with ThreadPoolExecutor(max_workers=args.workers) as pool:
                futures = {pool.submit(critic.critique, p, s, cond): (p, s)
                           for (p, s) in todo}
                errors = 0
                for future in tqdm(as_completed(futures), total=len(todo),
                                   desc=f"{arm}/{cond.value}"):
                    try:
                        logger.log_critique(future.result())
                    except Exception as e:
                        errors += 1
                        tqdm.write(f"[ERROR] {e}")
            if errors:
                print(f"  skipped {errors} items due to errors")

    print(f"\nDone. Outputs in {args.log_dir}/")


if __name__ == "__main__":
    main()
